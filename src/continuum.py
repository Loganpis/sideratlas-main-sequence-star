"""LTE H-minus continuum synthesis from unmodified Bifrost thermodynamics.
Coefficients adapted from Lightweaver (MIT); see licenses/Lightweaver-MIT.txt.
No surface pattern or motion is generated by this module.
"""
from pathlib import Path
import json,time,argparse
import numpy as np
from scipy.interpolate import CubicSpline, RegularGridInterpolator
from numba import njit,prange
ROOT=Path(__file__).resolve().parents[1]
H=6.62607015e-34; C=299792458.; K=1.380649e-23; ME=9.1093837015e-31; EV=1.602176634e-19
CO=json.loads((ROOT/'data/continuum-coefficients.json').read_text())
MU=np.array([.10,.30,.55,.78,1.])
AZ=np.arange(4)*np.pi/2
XYZ_RGB=np.array([[3.2404542,-1.5371385,-.4985314],[-.969266,1.8760108,.041556],[.0556434,-.2040259,1.0572252]])

def coefficients(wave,T):
    bf=CubicSpline(CO['lambdaBF'],CO['alphaBF'],bc_type='natural')(wave)*1e-21
    table=np.array(CO['kappaFF']).reshape(17,16)
    ff=RegularGridInterpolator((CO['lambdaFF'],CO['thetaFF']),table,bounds_error=True)
    theta=np.clip(5040/T,.5,2.)
    return bf,ff(np.stack((np.full(T.shape,wave),theta),axis=-1))*1e-29

@njit(parallel=True,cache=True)
def radiation_arrays(T,ne,nh,ff,bf,wave):
    a=np.empty_like(T);b=np.empty_like(T)
    t=T.ravel();e=ne.ravel();n=nh.ravel();f=ff.ravel();aa=a.ravel();bb=b.ravel()
    lam=wave*1e-9
    for j in prange(t.size):
        x=H*C/(lam*K*t[j]);stim=-np.expm1(-x)
        nminus=(n[j]*.25)*e[j]*(H*H/(2*np.pi*ME*K*t[j]))**1.5*np.exp(.754*EV/(K*t[j]))
        aa[j]=nminus*bf*stim+(n[j]*K)*e[j]*t[j]*f[j]
        bb[j]=2*H*C*C/lam**5/np.expm1(x)
    return a,b

@njit(cache=True)
def bilinear(a,k,x,y):
    ny,nx=a.shape[1:]; ix=int(np.floor(x));iy=int(np.floor(y));fx=x-ix;fy=y-iy
    i0=ix%nx;i1=(ix+1)%nx;j0=iy%ny;j1=(iy+1)%ny
    return (1-fy)*((1-fx)*a[k,j0,i0]+fx*a[k,j0,i1])+fy*((1-fx)*a[k,j1,i0]+fx*a[k,j1,i1])

@njit(parallel=True,cache=True)
def formal(chi,source,z,dx,mu,az,stride=2):
    nz,ny,nx=chi.shape;out=np.zeros((len(mu),len(az),ny//stride,nx//stride),np.float32)
    for q in prange(len(mu)*len(az)*(ny//stride)):
        j=q%(ny//stride);p=q//(ny//stride);ia=p%len(az);im=p//len(az)
        slope=np.sqrt(1-mu[im]**2)/mu[im]
        sx=slope*np.cos(az[ia])/dx;sy=slope*np.sin(az[ia])/dx
        for i in range(nx//stride):
            x=i*stride;y=j*stride
            xx=x+z[0]*sx;yy=y+z[0]*sy
            c0=bilinear(chi,0,xx,yy);s0=bilinear(source,0,xx,yy);iv=s0
            for k in range(1,nz):
                xx=x+z[k]*sx;yy=y+z[k]*sy
                c1=bilinear(chi,k,xx,yy);s1=bilinear(source,k,xx,yy)
                tau=.5*(c0+c1)*(z[k]-z[k-1])/mu[im]
                if tau<1e-4:
                    e=1+np.expm1(-tau);at=1-tau/2+tau*tau/6-tau**3/24
                else:
                    e=np.exp(-tau);at=-np.expm1(-tau)/tau
                iv=iv*e+s0*(at-e)+s1*(1-at)
                c0=c1;s0=s1
            out[im,ia,j,i]=iv
    return out

def inputs(snapshot):
    d=np.load(ROOT/f'data/raw/lgtg-{snapshot}.npz')
    T=np.power(10.,d['values']);ne=np.power(10.,np.load(ROOT/f'data/raw/lgne-{snapshot}.npz')['values']);nh=np.power(10.,np.load(ROOT/f'data/raw/lgn1-{snapshot}.npz')['values'])
    return T,ne,nh,(d['z_Mm']-.061)*1e6,float(d['dx_Mm'])*1e6,float(d['time_s']),float(d['source_teff_K'])

def spectral_weights(wave):
    """Fixed HSRS normalization of baseline disk-integrated continuum spectrum.
    Hybrid spectral response, not local line formation or a temperature fit.
    """
    import h5py
    baseline=np.load(ROOT/'data/continuum/385-17-2.npz')
    w0=baseline['wavelength_nm'];m=baseline['mu'];i0=baseline['mean_spectrum']
    flux0=2*np.pi*np.trapz(np.column_stack((i0[:,0],i0))*np.r_[0,m],np.r_[0,m],axis=1)
    with h5py.File(ROOT/'data/tsis1-hsrs-v2-1nm.nc') as f:
        w=np.array(f['Vacuum Wavelength']);ref=np.array(f['SSI'])*1e9*(149597870700./6.957e8)**2
    take=(w>=wave[0])&(w<=wave[-1]);w=w[take];ref=ref[take]
    cmf=np.loadtxt(ROOT/'data/CIE_xyz_1931_2deg.csv',delimiter=',')
    cie=np.stack([np.interp(w,cmf[:,0],cmf[:,j]) for j in [1,2,3]],axis=-1)
    correction=ref/np.interp(w,w0,flux0)
    basis=np.stack([np.interp(w,wave,np.eye(len(wave))[j]) for j in range(len(wave))],axis=-1)
    return np.trapz(basis[:,:,None]*cie[:,None,:]*correction[:,None,None],w*1e-9,axis=0)

def synthesize(snapshot,nwave=17,stride=2,calibrated=False):
    suffix='-solar' if calibrated else ''
    out=ROOT/f'data/continuum/{snapshot}-{nwave}-{stride}{suffix}.npz';out.parent.mkdir(exist_ok=True)
    if out.exists():return str(out)
    begin=time.monotonic();T,ne,nh,z,dx,t,teff=inputs(snapshot)
    wave=np.linspace(380,800,nwave)
    cie=np.loadtxt(ROOT/'data/CIE_xyz_1931_2deg.csv',delimiter=',')
    xyz=np.stack([np.interp(wave,cie[:,0],cie[:,i]) for i in [1,2,3]],axis=-1)
    dw=np.gradient(wave)*1e-9;dw[[0,-1]]*=.5
    weights=spectral_weights(wave) if calibrated else xyz*dw[:,None]
    xyzmap=np.zeros((len(MU),len(AZ),T.shape[1]//stride,T.shape[2]//stride,3),np.float32)
    spectra=[];checks={}
    # Avoid evaluating a 3D scipy interpolator: the tabulated free-free factor
    # is piecewise linear in theta, with wavelength fixed for each integration.
    theta=np.clip(5040/T,.5,2.)
    ff_wave=np.array(CO['kappaFF']).reshape(17,16)
    for iw,w in enumerate(wave):
        bf=CubicSpline(CO['lambdaBF'],CO['alphaBF'],bc_type='natural')(w)*1e-21
        frow=np.array([np.interp(w,CO['lambdaFF'],ff_wave[:,j]) for j in range(16)])
        ff=np.interp(theta,CO['thetaFF'],frow).astype('f4')*1e-29
        chi,S=radiation_arrays(T,ne,nh,ff,bf,w)
        imap=formal(chi,S,z,dx,MU,AZ,stride)
        xyzmap+=imap[...,None]*weights[iw].astype('f4')
        spectra.append(imap.mean(axis=(-1,-2,-3)))
        if iw==nwave//2:
            tau=np.trapz(chi,z,axis=0)
            checks={'minimum_bottom_tau':float(tau.min()),'median_bottom_tau':float(np.median(tau)), 'T_min_K':float(T.min()),'T_max_K':float(T.max()),'disk_center_contrast':float(imap[-1,0].std()/imap[-1,0].mean())}
        print(snapshot,'continuum',round(w,1),flush=True)
    rgb=np.einsum('...j,ij->...i',xyzmap,XYZ_RGB).astype('f4')
    np.savez_compressed(out,rgb=rgb,mu=MU,azimuth_rad=AZ,wavelength_nm=wave,mean_spectrum=np.array(spectra),time_s=t,source_teff_K=teff,dx_Mm=dx*stride/1e6)
    checks.update(solar_reference_calibration=calibrated,snapshot=snapshot,nwave=nwave,stride=stride,elapsed_s=time.monotonic()-begin,source_teff_K=teff,negative_RGB_fraction=float(np.mean(rgb<0)))
    out.with_suffix('.json').write_text(json.dumps(checks,indent=2)+'\n')
    print('Synthesized',out.name,checks,flush=True)
    return str(out)

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('snapshot',type=int);ap.add_argument('--nwave',type=int,default=17);ap.add_argument('--stride',type=int,default=2);a=ap.parse_args();synthesize(a.snapshot,a.nwave,a.stride)
